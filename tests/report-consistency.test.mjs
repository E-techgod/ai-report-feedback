import test from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { issueDownloadGrant } from '../src/lib/download-grant.ts';
import { generateReport } from '../src/lib/generate-report.ts';
import { fallbackNarrative } from '../src/lib/report.ts';
import { buildReportContent } from '../src/lib/report-content.ts';
import { handlePdfDownload } from '../src/lib/report-pdf-handler.ts';
import { freshLimiter } from './helpers/ledger.mjs';
import { reportDeps, submission } from './helpers/flow-harness.mjs';

test('web and PDF read the one generated report; the provider is called once', async () => {
  const h = reportDeps();
  const report = await generateReport(h.deps, submission());
  assert.equal(h.narrativeCalls.length, 1);
  assert.equal(buildReportContent(report).executive.summaryText, report.narrative.executiveSummary);

  const secret = 's'.repeat(32);
  const { token } = issueDownloadGrant(report, secret, h.deps.now());
  const rendered = [];
  const response = await handlePdfDownload(
    new Request('https://example.com/api/report/pdf', {
      method: 'POST',
      headers: { 'x-download-token': token },
      body: JSON.stringify(report),
    }),
    {
      secret,
      limiter: freshLimiter().limiter,
      now: h.deps.now,
      renderPdf: async (r) => (rendered.push(r), Buffer.from('%PDF-fake')),
    },
  );
  assert.equal(response.status, 200);
  assert.deepEqual(rendered, [report], 'the PDF is rendered from the same report');
  assert.equal(h.narrativeCalls.length, 1, 'downloading never calls the AI provider again');
});

test('a rate-limited AI run yields labelled template text and is not regenerated by downloads', async () => {
  const h = reportDeps({
    narrative: async (model) => ({
      narrative: fallbackNarrative(model),
      source: 'template',
      failureReason: 'rate-limited',
    }),
  });
  const report = await generateReport(h.deps, submission());
  assert.equal(report.narrativeSource, 'template');
  assert.equal(report.aiFailureReason, 'rate-limited');
});

test('AI provider keys and settings never reach the browser', () => {
  const root = new URL('../src', import.meta.url).pathname;
  const files = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.(ts|tsx)$/.test(name)) files.push(path);
    }
  };
  walk(root);
  const server = new Set(['narrative.ts']);
  for (const path of files) {
    const text = readFileSync(path, 'utf8');
    assert.ok(!/NEXT_PUBLIC_(GROQ|ANTHROPIC|AI_)/.test(text), `${path} exposes a key`);
    if (/^['"]use client['"]/m.test(text))
      assert.ok(!/GROQ_|ANTHROPIC_|AI_PROVIDER/.test(text), `${path} is a client component`);
    if (/GROQ_API_KEY/.test(text))
      assert.ok(
        server.has(path.split('/').pop()),
        `${path} reads the Groq key outside narrative.ts`,
      );
  }
  const example = readFileSync(new URL('../.env.example', import.meta.url), 'utf8');
  assert.ok(!/NEXT_PUBLIC_(GROQ|AI_)/.test(example));
});
